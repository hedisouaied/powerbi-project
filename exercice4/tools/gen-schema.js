// Generates backend/config/mission_control.php from exercice3's profiled schema (tools/schema.txt), its relationship
// list (tools/build-pbip.ps1 $rel) and the CSVs (max text lengths). Same tables, same columns, same relationships.
// Usage: node tools/gen-schema.js
"use strict";
const fs = require("fs"), path = require("path");
const ex4 = path.resolve(__dirname, ".."), ex3 = path.resolve(ex4, "..", "exercice3");
const data = path.join(ex4, "backend", "database", "data");
const schema = {};
fs.readFileSync(path.join(ex3, "tools", "schema.txt"), "utf8").split(/\r?\n/).forEach(l => {
    const [t, ...cols] = l.trim().split(/\s+/); if (!t) { return; }
    schema[t] = cols.map(c => { const i = c.lastIndexOf(":"); return { name: c.slice(0, i), type: c.slice(i + 1) }; });
});
// calendar_events.event_date is derived in Power Query (date part of start_datetime): a stored generated column here
const pbip = fs.readFileSync(path.join(ex3, "tools", "build-pbip.ps1"), "utf8");
const relBlock = pbip.slice(pbip.indexOf("$rel = @("), pbip.indexOf("\n)", pbip.indexOf("$rel = @(")));
const rels = [...relBlock.matchAll(/@\('([a-z_]+)\.([a-z_]+)', '([a-z_]+)\.([a-z_]+)', (\d)\)/g)].map(m => ({ table: m[1], column: m[2], refTable: m[3], refColumn: m[4], activeInPowerBI: m[5] === "1" }));
const DROP = { employees: ["monthly_salary_tnd"], sales_order_items: ["order_line_id"], payments: ["customer_id"], inventory_snapshots: ["inventory_snapshot_id"], kpi_targets: ["target_id"], calendar_events: ["data_origin"], expenses: ["reference_code"] };
const EDITABLE = ["tasks", "calendar_events", "approval_requests", "decisions", "collaboration_comments", "notifications", "investigation_cases", "alerts", "incidents", "products", "activity_log"];

function parseCsv(text) {
    const rows = []; let row = [], cell = "", q = false;
    for (let i = 0; i < text.length; i++) { const ch = text[i];
        if (q) { if (ch === '"') { if (text[i + 1] === '"') { cell += '"'; i++; } else { q = false; } } else { cell += ch; } continue; }
        if (ch === '"') { q = true; } else if (ch === ",") { row.push(cell); cell = ""; } else if (ch === "\n") { row.push(cell.replace(/\r$/, "")); rows.push(row); row = []; cell = ""; } else { cell += ch; } }
    if (cell || row.length) { row.push(cell.replace(/\r$/, "")); rows.push(row); }
    return rows.filter(r => r.length > 1 || r[0]);
}
const feeds = JSON.parse(fs.readFileSync(path.join(ex3, "tools", "feeds.json"), "utf8").replace(/^﻿/, ""));
const tables = {};
Object.keys(schema).forEach(t => {
    const rows = parseCsv(fs.readFileSync(path.join(data, `${t}.csv`), "utf8").replace(/^﻿/, ""));
    const head = rows[0].map(h => h.trim());
    const cols = schema[t].map(c => { const i = head.indexOf(c.name); const max = i < 0 ? 0 : Math.max(0, ...rows.slice(1).map(r => (r[i] ?? "").trim().length)); return { ...c, max }; });
    if (t === "calendar_events") { cols.push({ name: "event_date", type: "G", max: 0 }); }
    tables[t] = { primaryKey: head[0], columns: cols, rows: rows.length - 1, feed: feeds.includes(t), feedColumns: schema[t].map(c => c.name).filter(c => !(DROP[t] ?? []).includes(c)), editable: EDITABLE.includes(t) };
});
const php = (v, ind = "") => {
    if (Array.isArray(v)) { return v.length ? "[\n" + v.map(x => ind + "    " + php(x, ind + "    ")).join(",\n") + "\n" + ind + "]" : "[]"; }
    if (v && typeof v === "object") { return "[\n" + Object.entries(v).map(([k, x]) => `${ind}    '${k}' => ${php(x, ind + "    ")}`).join(",\n") + "\n" + ind + "]"; }
    if (typeof v === "string") { return `'${v.replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`; }
    return String(v);
};
const out = `<?php\n\n// GENERATED by exercice4/tools/gen-schema.js from exercice3 (schema.txt, build-pbip.ps1 relationships, CSVs). Do not edit by hand.\n// Types: S text, D date, T datetime, I integer, N double, C money (decimal), P ratio (double), B boolean, G generated (event_date).\n\nreturn ${php({ reference_date: "2026-11-22", tables, relationships: rels })};\n`;
fs.writeFileSync(path.join(ex4, "backend", "config", "mission_control.php"), out);
console.log(`${Object.keys(tables).length} tables (${feeds.length} feeds), ${rels.length} relationships, ${Object.values(tables).reduce((a, t) => a + t.rows, 0)} rows`);
